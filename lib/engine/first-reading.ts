export interface DayOutlook {
  dateISO: string;
  วัน: string;
  ธาตุประจำวัน: string;
  คะแนน: number; // wuXingScore -2..2
}

export interface WeekOutlook {
  รายวัน: DayOutlook[];
  วันเป็นมิตร: DayOutlook[]; // คะแนน > 0
  วันควรใจเย็น: DayOutlook[]; // คะแนน < 0
}

const THAI_DAYS = ["อาทิตย์", "จันทร์", "อังคาร", "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์"];

/** จังหวะ 7 วันข้างหน้า (เริ่มวันนี้ตามเวลาไทย UTC+7) — DAY_ELEMENT×wuXingScore engine ล้วน */
export function weekOutlook(dominant: Element5, missing: Element5[]): WeekOutlook {
  const BKK_MS = 7 * 3600_000;
  const days: DayOutlook[] = [];
  for (let i = 0; i < 7; i++) {
    const dt = new Date(Date.now() + BKK_MS + i * 86400_000);
    const dow = dt.getUTCDay();
    const dayName = THAI_DAYS[dow];
    const el = DAY_ELEMENT[dayName];
    if (!el) continue; // กันตารางไม่ครบ (ไม่ควรเกิด — B2 แก้แล้ว)
    const score = wuXingScore(dominant, el, missing).final_score;
    days.push({ dateISO: dt.toISOString().slice(0, 10), วัน: dayName, ธาตุประจำวัน: THAI_LABEL_5[el], คะแนน: score });
  }
  return {
    รายวัน: days,
    วันเป็นมิตร: days.filter((d) => d.คะแนน > 0),
    วันควรใจเย็น: days.filter((d) => d.คะแนน < 0),
  };
}

export interface FirstReading {
  ธาตุเด่น: string;
  นิสัยเด่น: string;
  พลังพิเศษ: string;
  ระวังนิสัย: string;
  อาชีพแนว: string[];
  จุดที่ควรฝึก: string[];
  สัปดาห์นี้: WeekOutlook;
}

export function buildFirstReading(dominant: Element5, missing: Element5[]): FirstReading {
  const p = ELEMENT_PERSONA[dominant];
  return {
    ธาตุเด่น: THAI_LABEL_5[dominant],
    นิสัยเด่น: p.นิสัยเด่น,
    พลังพิเศษ: p.พลังพิเศษ,
    ระวังนิสัย: p.ระวังนิสัย,
    อาชีพแนว: p.อาชีพแนว,
    จุดที่ควรฝึก: missing.map((m) => `ขาดธาตุ${THAI_LABEL_5[m]} → ${MISSING_GROWTH[m]}`),
    สัปดาห์นี้: weekOutlook(dominant, missing),
  };
}
