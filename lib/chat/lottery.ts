// ตัวดักคำถามขอ "เลขเด็ด/หวย" — นโยบายความรับผิดชอบ (ตรรกะล้วน เทสต์ได้)
//
// 🔴 จุดยืน: KRUTH ไม่ทำนายผลหวย/ล็อตเตอรี่ เพราะผลออกรางวัลเป็นการสุ่มล้วน ทำนายล่วงหน้าไม่ได้จริง
//    การอ้างว่าทำได้ = ขัดจุดขาย §0 ("คำนวณจริง ไม่ใช่การเดา") และไม่รับผิดชอบต่อผู้ใช้
//
// ⚠️ ต้องแยก "ขอเลขหวย" ออกจาก "เลขทะเบียน/เบอร์/เลขมงคล" (เรื่องที่เราคำนวณได้จริง)
//    → คำ **แข็ง** (หวยแน่ๆ) ดักเสมอ · คำ **อ่อน** (ก้ำกึ่ง เช่น "เลขเด็ด") ดักเฉพาะเมื่อ
//      ไม่มีบริบทเลขที่ถูกกฎหมาย (ทะเบียน/เบอร์/มงคล/ธาตุ) — "เลขเด็ดทะเบียนรถ" จึงผ่านไปคำนวณ
//
// ลำดับใน route: Safety Gate (วิกฤต) มาก่อนเสมอ → แล้วค่อยตัวนี้ → แล้วค่อย AI

// คำแข็ง = เกี่ยวหวย/ล็อตเตอรี่ชัดเจน → ดักทุกกรณี
const HARD_KEYWORDS = [
  "หวย",
  "ล็อตเตอรี่",
  "ลอตเตอรี่",
  "สลากกินแบ่ง",
  "สลากกิน",
  "เลขงวด",
  "งวดนี้",
  "งวดหน้า",
  "เลขที่จะออก",
  "เลขจะออก",
  "ถูกรางวัล",
  "ถูกหวย",
  "ยี่กี",
  "หุ้นหวย",
];

// คำอ่อน = ก้ำกึ่ง (มักหมายถึงหวย แต่ก็ใช้กับเลขมงคลได้) → ดักเฉพาะเมื่อไม่มีบริบทเลขที่ถูกกฎหมาย
const SOFT_KEYWORDS = ["เลขเด็ด", "เลขดัง", "เลขล็อก", "เลขเสี่ยงโชค", "เลขแม่น"];

// บริบทเลขที่ถูกกฎหมาย/คำนวณได้จริง → ถ้าเจอคู่กับคำอ่อน ให้ปล่อยผ่านไปคำนวณ
const LEGIT_CONTEXT = ["ทะเบียน", "เบอร์", "โทรศัพท์", "โทร", "ซิม", "บ้านเลขที่", "รถ", "แบรนด์", "มงคล", "ประจำตัว", "ธาตุ", "โลโก้"];

export const LOTTERY_MESSAGE =
  "ลาลาไม่ทำนายเลขหวยหรือผลรางวัลนะคะ 🙏 เพราะผลออกรางวัลเป็นการสุ่มล้วน " +
  "ไม่มีศาสตร์ไหนคำนวณล่วงหน้าได้จริง — ใครที่อ้างว่าบอกเลขถูกได้ ควรระวังไว้ค่ะ\n\n" +
  "LaLa Lucky Chat เน้น “การคำนวณจริง” เช่น ธาตุประจำตัว · ความเข้ากันของเลขทะเบียน/เบอร์โทร · " +
  "ฤกษ์ดี · โลโก้ตามธาตุ — เรื่องพวกนี้ลาลายินดีช่วยค่ะ\n\n" +
  "🎲 ถ้าเสี่ยงโชค โปรดเล่นอย่างมีสติและพอประมาณนะคะ";

export interface LotteryIntercept {
  declined: true;
  message: string;
}

/** คืนข้อความนโยบายถ้าเป็นการขอเลขหวย/ผลรางวัล · เลขทะเบียน/เบอร์/มงคล → null (ปล่อยผ่าน) */
export function lotteryIntercept(text: string): LotteryIntercept | null {
  if (HARD_KEYWORDS.some((k) => text.includes(k))) {
    return { declined: true, message: LOTTERY_MESSAGE };
  }
  const hasSoft = SOFT_KEYWORDS.some((k) => text.includes(k));
  const hasLegit = LEGIT_CONTEXT.some((k) => text.includes(k));
  if (hasSoft && !hasLegit) {
    return { declined: true, message: LOTTERY_MESSAGE };
  }
  return null;
}
