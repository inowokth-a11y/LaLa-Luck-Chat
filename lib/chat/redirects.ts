// ลำดับใน /api/chat: Safety Gate → lottery → **ตัวนี้** → gate ล็อกอิน/AI
// อยู่ก่อน AI = ไม่เสียเงิน ไม่คิดโควตา · ข้อความเป็นภาษาแม่หมอ (ไม่มีศัพท์ภายใน)

export interface ChatRedirect {
  kind: "medical" | "dream" | "timing" | "fengshui" | "oracle";
  message: string;
}

/**
 * คำถามผลการรักษา/การหายป่วย — แม่หมอห้ามทำนายแทนแพทย์ (กติกาเดียวกับ narrator ข้อ 4)
 * จับเฉพาะ "โรค + จะหายไหม/จะรอดไหม" — ไม่จับคำถามดูแลตัวเองทั่วไป (นั่นมี wellness ตอบได้)
 */
const MEDICAL_RE =
  /(มะเร็ง|เนื้องอก|โรคร้าย|ป่วยหนัก|ผ่าตัด|เคมีบำบัด|ติดเชื้อ|เบาหวาน|ไตวาย|หัวใจล้มเหลว).{0,30}(หายไหม|หายมั้ย|จะหาย|จะรอด|รักษาหาย|หายขาด)|(จะหายจากโรค|หายป่วยไหม|หายป่วยมั้ย)/;

/** เครื่องมือเฉพาะทางที่มีอยู่แล้ว — พาไปใช้ตรงๆ ดีกว่าตอบว่า "ยังไม่มีโหมด" */
