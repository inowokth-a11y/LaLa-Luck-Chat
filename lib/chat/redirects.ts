const MEDICAL_MESSAGE =
  "เรื่องการเจ็บป่วยและการรักษา แม่หมอทำนายแทนคุณหมอไม่ได้จริงๆ ค่ะ 🙏\n" +
  "การรักษากับแพทย์ผู้ดูแลคือทางที่ดีที่สุด และขอให้เชื่อมั่นในทีมแพทย์นะคะ\n\n" +
  "แม่หมอขอส่งกำลังใจให้เต็มที่เลยค่ะ 🐾 ถ้าอยากได้กิจกรรมดูแลใจตามธาตุของคุณในช่วงนี้ ถามแม่หมอได้เสมอนะคะ";

/**
 * ตรวจคำถามก่อนถึง AI — คืน null ถ้าไม่เข้าเคสไหน (ไปตามเส้นปกติ)
 * ⚠️ medical ต้องมาก่อน tool: "ผ่าตัดแล้วจะหายไหม ควรดูฤกษ์ผ่าตัดวันไหน" ให้ตอบแบบ medical
 */
export function chatRedirectIntercept(question: string): ChatRedirect | null {
  const q = question.trim();
  if (MEDICAL_RE.test(q)) return { kind: "medical", message: MEDICAL_MESSAGE };
  for (const rule of TOOL_RULES) {
    if (rule.re.test(q)) return { kind: rule.kind, message: rule.message };
  }
  return null;
}
